#!/usr/bin/env python3

import csv
import json
import os
from pathlib import Path
from urllib.parse import urlencode
from urllib.request import Request, urlopen


API_URL = "https://api.digitaltwins.iwmi.org/chatbot/rainfall_analyses"

STATION_NAME = "s24851s29487e"
CHANNEL_ID = "cha1099"

START_DATE = "2001-01-01"
END_DATE = "2026-09-30"

OUTPUT = Path(
    "integration/raw_data/iwmi_chokwe_monthly_rainfall_2001_2026_09.csv"
)

METADATA_OUTPUT = Path(
    "integration/raw_data/iwmi_chokwe_monthly_rainfall_2001_2026_09.metadata.json"
)


def fetch_json(url: str) -> dict:
    headers = {
        "Accept": "application/json",
        "User-Agent": "AgWise-IWMI-monthly-rainfall-export/1.0",
    }

    token = os.getenv("IWMI_BEARER_TOKEN")
    if token:
        headers["Authorization"] = "Bearer " + token

    request = Request(url, headers=headers)

    with urlopen(request, timeout=120) as response:
        return json.loads(response.read().decode("utf-8"))


def fetch_text(url: str) -> str:
    headers = {
        "Accept": "text/csv",
        "User-Agent": "AgWise-IWMI-monthly-rainfall-export/1.0",
    }

    token = os.getenv("IWMI_BEARER_TOKEN")
    if token:
        headers["Authorization"] = "Bearer " + token

    request = Request(url, headers=headers)

    with urlopen(request, timeout=120) as response:
        return response.read().decode("utf-8")


def parse_month(value):
    """
    Convert common API date formats to YYYY-MM.
    """
    if value is None:
        return None

    text = str(value).strip()

    if len(text) >= 7 and text[4] == "-":
        year_month = text[:7]
        if year_month[0:4].isdigit() and year_month[5:7].isdigit():
            return year_month

    return None


def extract_monthly_rainfall(csv_text):
    """Extract monthly totals from the CSV generated by the API."""
    records = csv.DictReader(
        line for line in csv_text.splitlines() if not line.startswith("#")
    )
    required_columns = {"month", "total_monthly_rain"}
    if not records.fieldnames or not required_columns.issubset(records.fieldnames):
        raise RuntimeError(
            "IWMI generated CSV must contain month and total_monthly_rain "
            f"columns; got {records.fieldnames!r}."
        )

    monthly = {}
    for record in records:
        month = parse_month(record["month"])
        if month is None:
            raise ValueError(f"Invalid month in IWMI CSV: {record['month']!r}")

        try:
            rainfall = float(record["total_monthly_rain"])
        except (TypeError, ValueError) as error:
            raise ValueError(
                f"Invalid rainfall value for {month}: "
                f"{record['total_monthly_rain']!r}"
            ) from error

        if rainfall < 0:
            raise ValueError(
                f"Negative rainfall returned for {month}: {rainfall}"
            )

        if month in monthly and abs(monthly[month] - rainfall) > 1e-9:
            raise ValueError(
                f"Conflicting rainfall values returned for {month}: "
                f"{monthly[month]} and {rainfall}"
            )

        monthly[month] = rainfall

    if not monthly:
        raise RuntimeError("IWMI generated CSV contained no rainfall rows.")

    return monthly


def expected_months(start_month: str, end_month: str):
    start_year, start_mon = map(int, start_month.split("-"))
    end_year, end_mon = map(int, end_month.split("-"))

    year = start_year
    month = start_mon

    result = []

    while (year, month) <= (end_year, end_mon):
        result.append(f"{year:04d}-{month:02d}")

        month += 1
        if month == 13:
            year += 1
            month = 1

    return result


def main():
    query = urlencode(
        {
            "station_name": STATION_NAME,
            "channel_id": CHANNEL_ID,
            "start_date": START_DATE,
            "end_date": END_DATE,
        }
    )

    url = f"{API_URL}?{query}"

    print(f"Requesting: {url}")

    payload = fetch_json(url)

    raw_output = OUTPUT.with_suffix(".raw.json")
    raw_output.parent.mkdir(parents=True, exist_ok=True)
    raw_output.write_text(
        json.dumps(payload, indent=2) + "\n",
        encoding="utf-8",
    )

    csv_url = payload.get("csv_url")
    if not isinstance(csv_url, str) or not csv_url:
        raise RuntimeError(
            "IWMI analysis response did not contain a csv_url. "
            f"Raw response saved to: {raw_output}"
        )

    csv_text = fetch_text(csv_url)
    csv_raw_output = OUTPUT.with_suffix(".source.csv")
    csv_raw_output.write_text(csv_text, encoding="utf-8")
    monthly = extract_monthly_rainfall(csv_text)

    expected = expected_months("2001-01", "2026-09")
    missing = [month for month in expected if month not in monthly]

    if missing:
        raise RuntimeError(
            "The API response is missing these requested months:\n"
            + ", ".join(missing)
            + f"\nRaw response saved to: {raw_output}"
        )

    selected = {
        month: monthly[month]
        for month in expected
    }

    with OUTPUT.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=["month", "rainfall_mm"],
        )
        writer.writeheader()

        for month, rainfall in selected.items():
            writer.writerow(
                {
                    "month": month,
                    "rainfall_mm": f"{rainfall:.6f}",
                }
            )

    metadata = {
        "source_url": API_URL,
        "station_name": STATION_NAME,
        "channel_id": CHANNEL_ID,
        "returned_station_name": payload.get("provenance", {}).get(
            "stationName"
        ),
        "returned_channel_id": payload.get("provenance", {}).get(
            "channelId"
        ),
        "requested_start": START_DATE,
        "requested_end": END_DATE,
        "coverage_start": expected[0],
        "coverage_end": expected[-1],
        "record_count": len(selected),
        "unit": "mm",
        "daily_observations": False,
        "description": (
            "Monthly IWMI rainfall analysis values. These are monthly totals "
            "used as constraints for synthetic daily rainfall generation."
        ),
        "raw_response": str(raw_output),
        "source_csv": str(csv_raw_output),
        "source_csv_url": csv_url,
    }

    METADATA_OUTPUT.write_text(
        json.dumps(metadata, indent=2) + "\n",
        encoding="utf-8",
    )

    print(f"Wrote CSV: {OUTPUT}")
    print(f"Wrote metadata: {METADATA_OUTPUT}")
    print(f"Wrote raw response: {raw_output}")
    print(f"Monthly records: {len(selected)}")
    print(f"Coverage: {expected[0]} through {expected[-1]}")


if __name__ == "__main__":
    main()